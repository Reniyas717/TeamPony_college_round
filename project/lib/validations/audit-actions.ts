export function allowlistedAuditMetadata(action: AuditAction, metadata: Record<string, unknown>) {
  const allowed = new Set(METADATA_KEYS[action] ?? COMMON);
  return Object.fromEntries(Object.entries(metadata).filter(([key]) => allowed.has(key)));
}
